// Обчислити площу трикутника, якщо трикутник задано довжиною однієї з сторін та висотою, опущеною на неї[cite: 52].

#include <iostream>

using namespace std;

int main() {
    // a — довжина сторони трикутника, h — висота, опущена на цю сторону
    double a, h;

    cout << "Введіть довжину сторони трикутника: ";
    cin >> a;

    cout << "Введіть висоту, опущену на цю сторону: ";
    cin >> h;

    // Перевірка геометричної коректності вхідних даних (довжини мають бути додатними)
    if (a <= 0.0 || h <= 0.0) {
        cout << "Помилка: сторона та висота мають бути строго більшими за нуль!" << endl;
        return 1;
    }

    // Обчислення площі за формулою: S = (a * h) / 2
    double S = 0.5 * a * h;

    // Виведення результату
    cout << "Площа трикутника = " << S << endl;

    return 0; // Успішне завершення програми
}
