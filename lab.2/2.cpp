// Умова (Варіант 3):
// Обчислити значення кусково-заданої функції y:
// y = cos(x^2 + ln(x)), якщо x^2 + ln(x) > 0
// y = 1 / (x^2 + ln(x)), якщо x^2 + ln(x) < 0
// y = cos(x), якщо x^2 + ln(x) == 0

#include <iostream>
#include <cmath>

using namespace std;

int main() {
    // Змінна для вхідного дійсного числа
    double x;

    cout << "Введіть x: ";
    cin >> x;

    // Область допустимих значень: аргумент натурального логарифма ln(x) повинен бути строго додатним
    if (x <= 0.0) {
        cout << "Помилка: x має бути більшим за 0 (область визначення ln(x))." << endl;
        return 1;
    }

    // Обчислюємо значення виразу x^2 + ln(x), щоб уникнути дублювання обчислень
    double expr = x * x + log(x);
    double y;

    // Перевірка умов розгалуження
    if (expr > 0.0) {
        // Перший випадок: вираз строго більший за 0
        y = cos(expr);
    } else if (expr < 0.0) {
        // Другий випадок: вираз строго менший за 0 (ділення на нуль виключено)
        y = 1.0 / expr;
    } else {
        // Третій випадок: вираз дорівнює 0
        y = cos(x);
    }

    // Виведення отриманого результату
    cout << "y = " << y << endl;

    return 0; // Успішне завершення програми
}
