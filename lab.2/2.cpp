// Условие (Вариант 3):
// Вычислить значение кусочно-заданной функции y:
// y = cos(x^2 + ln(x)), если x^2 + ln(x) > 0
// y = 1 / (x^2 + ln(x)), если x^2 + ln(x) < 0
// y = cos(x), если x^2 + ln(x) == 0

#include <iostream>
#include <cmath>

using namespace std;

int main() {
    // Переменная для входного вещественного числа
    double x;

    cout << "Введите x: ";
    cin >> x;

    // Область допустимых значений: аргумент натурального логарифма ln(x) должен быть строго положительным
    if (x <= 0.0) {
        cout << "Ошибка: x должен быть больше 0 (область определения ln(x))." << endl;
        return 1;
    }

    // Вычисляем значение выражения x^2 + ln(x), чтобы не дублировать вычисления
    double expr = x * x + log(x);
    double y;

    // Проверка условий ветвления
    if (expr > 0.0) {
        // Первый случай: выражение строго больше 0
        y = cos(expr);
    } else if (expr < 0.0) {
        // Второй случай: выражение строго меньше 0 (деление на ноль исключено)
        y = 1.0 / expr;
    } else {
        // Третий случай: выражение равно 0
        y = cos(x);
    }

    // Вывод полученного результата
    cout << "y = " << y << endl;

    return 0; // Успешное завершение программы
}
