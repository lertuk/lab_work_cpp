// Умова (Варіант 3):
// e^(-x) = \sum_{n=0}^{\infty} ((-1)^n * x^n) / n! = 1 - x + x^2/2! - x^3/3! + x^4/4! - ...[cite: 51]
// Обчислити значення функції за допомогою розкладу в степеневий ряд із заданою точністю eps[cite: 51].

#include <iostream>
#include <cmath>

using namespace std;

int main() {
    // x — точка обчислення, eps — задана точність (наприклад, 0.0001)
    double x, eps;

    cout << "Введіть значення x та точність eps: ";
    cin >> x >> eps;

    // Перевірка коректності заданої точності
    if (eps <= 0.0) {
        cout << "Точність eps має бути строго більшою за 0." << endl;
        return 1;
    }

    // Змінна для накопичення суми ряду
    double sum = 0.0;

    // Перший доданок ряду при n = 0: (-1)^0 * x^0 / 0! = 1
    double term = 1.0;

    // Номер поточного члена ряду
    int n = 0;

    // Додаємо члени ряду, поки абсолютна величина доданка більша або рівна eps
    while (abs(term) >= eps) {
        sum += term;
        ++n;

        // Рекурентне обчислення наступного доданка:
        // term_n = term_{n-1} * (-x / n)
        term = -term * x / n;
    }

    // Виведення результатів обчислення
    cout << "Наближене значення e^(-" << x << ") за рядом = " << sum << endl;
    cout << "Точне значення через exp(-" << x << ")        = " << exp(-x) << endl;
    cout << "Кількість врахованих доданків              = " << n << endl;

    return 0; // Успішне завершення програми
}
