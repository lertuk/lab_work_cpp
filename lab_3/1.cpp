// Умова (Варіант 3):
// Дано a ∈ R, n ∈ N. Знайти суму n доданків:
// 1! / a^2 + 2! / (a^3 * (a + 1)) + 3! / (a^4 * (a + 1)^2 * (a + 2)) + ...[cite: 50]

#include <iostream>

using namespace std;

int main() {
    // a — дійсне число, n — кількість доданків
    double a;
    int n;

    cout << "Введіть a та n: ";
    cin >> a >> n;

    // Перевірка коректності кількості доданків
    if (n <= 0) {
        cout << "Кількість доданків має бути натуральним числом (n > 0)." << endl;
        return 0;
    }

    // Перевірка ділення на нуль для першого елемента
    if (a == 0.0) {
        cout << "Помилка: знаменник дорівнює нулю при a = 0." << endl;
        return 1;
    }

    // Змінна для накопичення суми
    double sum = 0.0;

    // Перший член ряду при k = 1: 1! / a^2
    double term = 1.0 / (a * a);

    // Допоміжний множник для знаменника:
    // На кожному кроці k знаменник домножується на a * (a + 1) * ... * (a + k - 1)
    double p = a;

    // Додаємо перший доданок до загальної суми
    sum += term;

    // Послідовно обчислюємо та додаємо решту доданків від 2 до n
    for (int k = 2; k <= n; ++k) {
        // Перевірка ділення на нуль для множника (a + k - 1)
        if (a + k - 1 == 0.0) {
            cout << "Помилка: знаменник дорівнює нулю на кроці k = " << k << endl;
            return 1;
        }

        // Оновлюємо множник p: p_k = p_{k-1} * (a + k - 1)
        p *= (a + k - 1);

        // Рекурентний зв'язок між сусідніми доданками:
        // term_k = term_{k-1} * k / p_k
        term = term * k / p;

        // Додаємо поточний доданок до суми
        sum += term;
    }

    // Виведення підсумкової суми
    cout << "Сума " << n << " доданків = " << sum << endl;

    return 0; // Успішне завершення програми
}
